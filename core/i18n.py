def _normalize_lang(lang):
    lang = (lang or "uz").lower()
    return lang if lang in MONTH_NAMES else "uz"


def get_month_name(month, lang="uz", short=False):
    try:
        idx = int(month) - 1
    except Exception:
        return str(month)
    if not (0 <= idx < 12):
        return str(month)
    lang = _normalize_lang(lang)
    names = MONTH_NAMES_SHORT if short else MONTH_NAMES
    return names[lang][idx]


def format_month_year(year, month, lang="uz", short=False):
    name = get_month_name(month, lang, short=short)
    return f"{name} {year}"


def format_day_month(day_value, lang="uz"):
    """Format: DD-MMM (localized short month)."""
    return f"{day_value.day:02d}-{get_month_name(day_value.month, lang, short=True)}"


