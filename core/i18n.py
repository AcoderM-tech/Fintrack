# Demo/system account names that can be translated at display time.
# Real user-defined account names should remain as-is.
SYSTEM_ACCOUNT_NAMES = {
    "Asosiy karta",
    "Naqd pul",
    "Jamg'arma",
    "USD karta",
}


def translate_account_name(name, lang):
    """Translate an account name only if it matches a known demo/system name."""
    if not name:
        return name
    lang = (lang or "uz").lower()
    if lang == "uz":
        return name
    if name not in SYSTEM_ACCOUNT_NAMES:
        return name
    return translate(name, lang)


def translate_category(name, lang):
    """Translate a category name only if it is a system/default category."""
    if not name:
        return name
    lang = (lang or "uz").lower()
    if lang == "uz":
        return name
    return SYSTEM_CATEGORY_NAMES.get(lang, {}).get(name, name)


def translate(text, lang):
    if not text:
        return text
    if not isinstance(text, str):
        text = str(text)
    lang = (lang or "uz").lower()
    return TRANSLATIONS.get(lang, {}).get(text, text)


def get_request_lang(request):
    """Request dan joriy tilni olish."""
    lang = None
    if request:
        # IMPORTANT: mirror {% t %} tag behavior.
        # If request.LANGUAGE_CODE is unset or is default ("uz"), allow cookie/session/profile to override.
        lang = (getattr(request, "LANGUAGE_CODE", "") or "").strip().lower()
        if lang in ("ru", "en"):
            return lang

        cookie_lang = request.COOKIES.get("fintrack_lang", "").strip().lower()
        if cookie_lang in ("uz", "ru", "en") and cookie_lang != "uz":
            return cookie_lang

        session_lang = (request.session.get("django_language") or "").strip().lower()
        if session_lang in ("uz", "ru", "en") and session_lang != "uz":
            return session_lang

        if getattr(request, "user", None) and request.user.is_authenticated:
            try:
                profile_lang = (request.user.profile.language or "").strip().lower()
                if profile_lang in ("uz", "ru", "en") and profile_lang != "uz":
                    return profile_lang
            except Exception:
                pass
    return lang if lang in ("uz", "ru", "en") else "uz"


def t(request, text, **kwargs):
    """View ichida ishlatish uchun tarjima funksiyasi."""
    lang = get_request_lang(request)
    result = translate(text, lang)
    if kwargs:
        try:
            result = result.format(**kwargs)
        except Exception:
            pass
    return result
